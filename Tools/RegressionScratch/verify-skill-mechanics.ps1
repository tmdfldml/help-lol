$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$source = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'artifacts/skill-source-cache/16.17.1/championFull.json') | ConvertFrom-Json
$ids = (Get-Content -Raw -Encoding UTF8 (Join-Path $root 'Data/Champions/champions.ko.json') | ConvertFrom-Json).champions.id
$keys = @('Q','W','E','R')
$rows = @()
$fields = @{}
foreach ($id in $ids) {
    $data = Get-Content -Raw -Encoding UTF8 (Join-Path $root "Data/ChampionSkills/$id.json") | ConvertFrom-Json
    if ($data.schemaVersion -ne 2 -or $data.championId -ne $id -or $data.spells.Count -ne 4) { throw "Invalid header: $id" }
    if (($data.spells.key -join '/') -ne 'Q/W/E/R') { throw "Invalid/duplicate mapping: $id" }
    for ($i=0; $i -lt 4; $i++) {
        $raw = $source.data.$id.spells[$i]
        foreach ($p in $raw.psobject.Properties) { $fields[$p.Name] = 1 }
        $s = $data.spells[$i]
        $entry = "$id.$($keys[$i])"
        if ($s.cooldownType -notin @('Standard','Charge','Toggle','ResourceBased','Passive','NotApplicable','Unknown')) { throw "Unknown enum: $entry" }
        if ($s.cooldowns -ne $null) {
            if (($s.cooldowns -join '/') -ne ($raw.cooldown -join '/')) { throw "Invented cast timer: $entry" }
            if ($s.cooldowns.Count -ne $raw.maxrank) { throw "Rank mismatch: $entry" }
            if (@($s.cooldowns | Where-Object { $_ -le 0 }).Count -gt 0 -and $entry -ne 'Urgot.W') { throw "Zero timer: $entry" }
        }
        if ($s.cooldownType -eq 'Standard' -and $s.cooldowns -eq $null) { throw "Missing standard timer: $entry" }
        if ($s.cooldownType -ne 'Charge' -and ($s.rechargeTimes -ne $null -or $s.maxCharges -ne $null)) { throw "Misplaced charge data: $entry" }
        # This pinned document contains no resolved numeric recharge variables. This
        # assertion prevents copying a cast cooldown into the recharge array.
        if ($s.rechargeTimes -ne $null) { throw "Recharge requires new resolved Riot source evidence: $entry" }
        if ($s.baseCooldowns -ne $null -and ($entry -ne 'Syndra.Q' -or ($s.baseCooldowns -join '/') -ne ($raw.cooldown -join '/'))) { throw "Invalid base timer: $entry" }
        if ([string]::IsNullOrWhiteSpace($s.sourceEvidence)) { throw "Missing evidence: $entry" }
        $rows += [pscustomobject]@{ Champion=$id; Skill=$keys[$i]; Type=$s.cooldownType; MaxCharges=$s.maxCharges; RechargeTime='Unknown'; CastCooldown=if($s.cooldowns -ne $null){$s.cooldowns -join ' / '}else{'Unknown'}; Evidence=$s.sourceEvidence }
    }
}
if ($ids.Count -ne 173 -or @($ids|Select-Object -Unique).Count -ne 173 -or $rows.Count -ne 692) { throw 'Coverage mismatch' }
$rows | Group-Object Type | Select-Object Name,Count | Format-Table -AutoSize
Write-Output ('Actual spell fields: ' + (($fields.Keys | Sort-Object) -join ', '))
$charge = @($rows | Where-Object Type -eq 'Charge')
if ($charge.Count -ne 19) { throw 'Charge audit changed; review required' }
$table = @('| Champion | Skill | Max charges | Recharge time | Cast cooldown (seconds) | Source evidence |', '|---|---|---|---|---|---|')
foreach ($row in $charge) {
    $max = if ($row.MaxCharges) { $row.MaxCharges } else { 'Unknown' }
    $table += "| $($row.Champion) | $($row.Skill) | $max | $($row.RechargeTime) | $($row.CastCooldown) | $($row.Evidence) |"
}
[IO.File]::WriteAllLines((Join-Path $root 'docs/charge-skills-16.17.1.md'), @('# Riot 16.17.1 charge spell audit', '', 'Generated by `Tools/RegressionScratch/verify-skill-mechanics.ps1`. All 692 source slots are checked; 19 charge slots include conditional Syndra Q. Unknown means unresolved, never zero seconds. Source: https://ddragon.leagueoflegends.com/cdn/16.17.1/data/ko_KR/championFull.json', '') + $table, [Text.UTF8Encoding]::new($false))
Write-Output 'PASS: 173 champions / 692 spells; unique QWER; exact source cooldowns; no invented recharge; malformed/duplicate/zero checks'
